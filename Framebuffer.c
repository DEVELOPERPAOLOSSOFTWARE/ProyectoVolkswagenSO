#define FONT_W  8
#define FONT_H  8

/* -------------------------------------------------------------------------
 * fb_init -- inicializar el driver de pantalla
 * ------------------------------------------------------------------------- */
void fb_init(void)
{
    uart_puts("[fb] Iniciando framebuffer...\n");
    uart_puts("[fb] Resolucion: ");

    /* Imprimir resolucion de hw_config.h */
    char buf[8]; int i;
    unsigned int tmp;

    tmp = HW_FB_WIDTH; i = 0;
    while (tmp) { buf[i++] = '0' + (tmp % 10); tmp /= 10; }
    for (int a=0,b=i-1; a<b; a++,b--) { char t=buf[a]; buf[a]=buf[b]; buf[b]=t; }
    buf[i] = '\0'; uart_puts(buf);
    uart_puts("x");
    tmp = HW_FB_HEIGHT; i = 0;
    while (tmp) { buf[i++] = '0' + (tmp % 10); tmp /= 10; }
    for (int a=0,b=i-1; a<b; a++,b--) { char t=buf[a]; buf[a]=buf[b]; buf[b]=t; }
    buf[i] = '\0'; uart_puts(buf);
    uart_puts(" @ 32bpp\n");

    /* Limpiar pantalla con color de fondo del OS */
    fb_clear(FB_VW_DARK);

    /* Pantalla de bienvenida minima */
    /* Barra superior azul VW */
    fb_fill_rect(0, 0, HW_FB_WIDTH, 48, FB_VW_BLUE);

    /* Titulo */
    fb_draw_string(16, 16, "VW OS Kernel  |  Bare-metal ARM64  |  PaolosSoftware",
                   FB_WHITE, FB_VW_BLUE);

    /* Linea separadora */
    fb_draw_hline(0, 49, HW_FB_WIDTH, FB_SILVER);

    /* Info de boot */
    fb_draw_string(16, 64,  "Kernel: boot > MMU > GIC > Timer > Scheduler > Framebuffer",
                   FB_SILVER, FB_VW_DARK);
    fb_draw_string(16, 80,  "Status: OK - Sistema operativo propio activo",
                   FB_GREEN,  FB_VW_DARK);
    fb_draw_string(16, 96,  "Hardware target: [ PENDIENTE - datasheet VW ]",
                   FB_SILVER, FB_VW_DARK);

    /* Barra inferior */
    fb_fill_rect(0, HW_FB_HEIGHT - 28, HW_FB_WIDTH, 28, FB_GRAY);
    fb_draw_string(16, HW_FB_HEIGHT - 20,
                   "PaolosSoftware  /  100% bare-metal  /  Sin Linux  /  Sin dependencias",
                   FB_SILVER, FB_GRAY);

    uart_puts("[fb] Framebuffer activo. Pantalla de bienvenida dibujada.\n");
}

/* -------------------------------------------------------------------------
 * Primitivas graficas
 * ------------------------------------------------------------------------- */

int fb_width(void)  { return HW_FB_WIDTH;  }
int fb_height(void) { return HW_FB_HEIGHT; }

void fb_put_pixel(int x, int y, unsigned int color)
{
    if ((unsigned int)x >= HW_FB_WIDTH || (unsigned int)y >= HW_FB_HEIGHT) return;
    fb[y * HW_FB_WIDTH + x] = color;
}

void fb_clear(unsigned int color)
{
    unsigned int total = HW_FB_WIDTH * HW_FB_HEIGHT;
    for (unsigned int i = 0; i < total; i++) {
        fb[i] = color;
    }
}

void fb_fill_rect(int x, int y, int w, int h, unsigned int color)
{
    for (int row = y; row < y + h; row++) {
        for (int col = x; col < x + w; col++) {
            fb_put_pixel(col, row, color);
        }
    }
}

void fb_draw_hline(int x, int y, int len, unsigned int color)
{
    for (int i = x; i < x + len; i++) fb_put_pixel(i, y, color);
}

void fb_draw_vline(int x, int y, int len, unsigned int color)
{
    for (int i = y; i < y + len; i++) fb_put_pixel(x, i, color);
}

void fb_draw_rect_outline(int x, int y, int w, int h, unsigned int color)
{
    fb_draw_hline(x,       y,       w, color);
    fb_draw_hline(x,       y+h-1,   w, color);
    fb_draw_vline(x,       y,       h, color);
    fb_draw_vline(x+w-1,   y,       h, color);
}

void fb_draw_char(int x, int y, char c, unsigned int fg, unsigned int bg)
{
    if (c < 32 || c > 127) c = '?';
    const unsigned char *glyph = font8x8[c - 32];

    for (int row = 0; row < FONT_H; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < FONT_W; col++) {
            unsigned int color = (bits & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
        }
    }
}

void fb_draw_string(int x, int y, const char *str, unsigned int fg, unsigned int bg)
{
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx  = x;
            y  += FONT_H + 2;
        } else {
            fb_draw_char(cx, y, *str, fg, bg);
            cx += FONT_W;
        }
        str++;
    }
}